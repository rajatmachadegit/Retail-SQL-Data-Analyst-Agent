import json
from langgraph.graph import StateGraph, END
from src.memory import AgentState
from src.tiger_gateway_client import TigerGatewayClient
from src.sql_tools import SQLDatabaseTool

# Initialize our LLM Client
llm_client = TigerGatewayClient()

# System Prompt detailing database schemas so the LLM writes exact SQL queries
DB_SCHEMA_PROMPT = """You are an expert SQL Generator for a retail sales database.
Your job is to translate natural English questions into highly accurate, read-only MySQL SELECT queries.

### Database Schema Reference:
1. STORES
- store_id (VARCHAR PRIMARY KEY)
- store_name (VARCHAR)
- region (VARCHAR)
- city (VARCHAR)
- store_type (VARCHAR)

2. PRODUCTS
- product_id (VARCHAR PRIMARY KEY)
- product_name (VARCHAR)
- category (VARCHAR)
- sub_category (VARCHAR)
- base_price (DECIMAL)

3. CUSTOMERS
- customer_id (VARCHAR PRIMARY KEY)
- customer_segment (VARCHAR)
- signup_date (DATE)
- preferred_channel (VARCHAR)
- city (VARCHAR)

4. SALES_TRANSACTIONS
- order_id (VARCHAR PRIMARY KEY)
- order_date (DATE)
- store_id (VARCHAR, FK to stores)
- product_id (VARCHAR, FK to products)
- customer_id (VARCHAR, FK to customers)
- sales_channel (VARCHAR)
- units_sold (INT)
- unit_price (DECIMAL)
- discount_pct (DECIMAL)
- payment_status (VARCHAR)
- delivery_status (VARCHAR)

5. RETURNS
- return_id (VARCHAR PRIMARY KEY)
- order_id (VARCHAR, FK to sales_transactions)
- return_date (DATE)
- return_reason (VARCHAR)

### SQL Writing Constraints:
- Use standard MySQL syntax.
- Ensure all queries are READ-ONLY. Do NOT generate INSERT, UPDATE, DELETE, or DROP statements.
- Return ONLY the executable SQL query. Do NOT wrap it in markdown code blocks, do not use ```sql...```, and do not provide explanations.
- When generating dates, use standard YYYY-MM-DD formatting.
- For conversational follow-ups, evaluate the past history to understand context.
"""

def generate_sql_node(state: AgentState) -> dict:
    """Node: Uses LLM to translate natural language user questions into MySQL query."""
    print("\n[Node 1: SQL Generation] Generating query...")

    # Structure user prompt including prior chat history to handle follow-up queries
    history_text = ""
    if state.get("history"):
        history_text = "\n### Past Conversation History for Context:\n"
        for turn in state["history"]:
            history_text += f"{turn['role'].capitalize()}: {turn['content']}\n"

    user_prompt = f"{history_text}\nUser's Current Question: {state['user_question']}\nSQL Query:"

    raw_query = llm_client.generate_response(system_prompt=DB_SCHEMA_PROMPT, user_prompt=user_prompt)

    # Programmatic cleaning to strip markdown formatting wrapper if LLM includes it
    cleaned_query = raw_query.replace("```sql", "").replace("```", "").strip()

    # Strip trailing semicolon for uniformity in validation checks
    if cleaned_query.endswith(";"):
        cleaned_query = cleaned_query[:-1]

    print(f"Generated Query: {cleaned_query}")
    return {"sql_query": cleaned_query}


def execute_sql_node(state: AgentState) -> dict:
    """Node: Runs safe SQL query against the retail database."""
    print("[Node 2: SQL Execution] Executing database tool...")

    query = state.get("sql_query")
    if not query:
        return {
            "query_status": "error",
            "error_message": "No query generated by LLM node.",
            "query_results": [],
            "columns": []
        }

    # Execute query using secure database tool wrapper
    execution_result = SQLDatabaseTool.execute_query(query)

    return {
        "query_status": execution_result["status"],
        "query_results": execution_result["results"],
        "columns": execution_result["columns"],
        "error_message": execution_result["message"] if execution_result["status"] != "success" else None
    }


def generate_answer_node(state: AgentState) -> dict:
    """Node: Synthesizes database findings into a natural English business answer."""
    print("[Node 3: Result Summarization] Formatting final response...")

    status = state.get("query_status")
    question = state.get("user_question")
    results = state.get("query_results")

    summarization_system_prompt = (
        "You are a friendly, professional Retail SQL Business Analyst. "
        "Your task is to take a business user's question and the raw relational "
        "data retrieved from SQL, and translate it into a concise, natural, "
        "and direct business response."
    )

    # Scenario A: SQL Execution Failed due to syntax error
    if status == "error":
        user_prompt = f"The user asked: '{question}'. The database returned a syntax error: '{state.get('error_message')}'. Please politely explain that we ran into a system execution error and cannot retrieve the results right now."
        final_answer = llm_client.generate_response(system_prompt=summarization_system_prompt, user_prompt=user_prompt)

    # Scenario B: Guardrail caught a security violation
    elif status == "rejected":
        final_answer = f"Security Violation: {state.get('error_message')}"

    # Scenario C: Success with empty dataset (no matches)
    elif status == "success" and not results:
        user_prompt = f"The user asked: '{question}'. The database search was successful but returned 0 rows matching their criteria. Formulate a polite message explaining no matches were found."
        final_answer = llm_client.generate_response(system_prompt=summarization_system_prompt, user_prompt=user_prompt)

    # Scenario D: Success with records retrieved
    else:
        # Convert first 20 records to a readable JSON dump to pass context directly
        data_dump = json.dumps(results[:20], default=str)
        user_prompt = f"User Question: {question}\nSQL Query Run: {state.get('sql_query')}\nRetrieved Database Records (JSON format):\n{data_dump}\n\nPlease draft a clean natural answer based on these findings:"
        final_answer = llm_client.generate_response(system_prompt=summarization_system_prompt, user_prompt=user_prompt)

    print("Final Business Answer Prepared.")

    # Prepare update payload for running chat memory log
    history_update = list(state.get("history", []))
    history_update.append({"role": "user", "content": question})
    history_update.append({"role": "assistant", "content": final_answer})

    return {"final_answer": final_answer, "history": history_update}


# --- Assemble the LangGraph State Machine ---
workflow = StateGraph(AgentState)

# 1. Add Operational Nodes
workflow.add_node("generate_sql", generate_sql_node)
workflow.add_node("execute_sql", execute_sql_node)
workflow.add_node("generate_answer", generate_answer_node)

# 2. Map Linear Workflow Path (Start -> SQL Gen -> Query Execute -> Response Summarize -> Complete)
workflow.set_entry_point("generate_sql")
workflow.add_edge("generate_sql", "execute_sql")
workflow.add_edge("execute_sql", "generate_answer")
workflow.add_edge("generate_answer", END)

# 3. Compile the Executable Workflow Graph
agent_graph = workflow.compile()